const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),config=JSON.parse(fs.readFileSync(path.join(root,'firebase.json'),'utf8'));
assert.equal(config.hosting.public,'site-dist');
const headers=Object.fromEntries(config.hosting.headers.find(x=>x.source==='**').headers.map(x=>[x.key,x.value]));
assert.equal(headers['X-Frame-Options'],'DENY');assert(headers['Content-Security-Policy'].includes("frame-ancestors 'none'"));
const workflow=fs.readFileSync(path.join(root,'.github/workflows/android.yml'),'utf8');
assert(workflow.includes('pull_request:'));assert(workflow.includes('pnpm test:rules'));
assert(workflow.indexOf('Deploy canonical Firebase workspace')<workflow.indexOf('Package Pages entry'));
assert(workflow.includes('with: {path: pages-dist}'));
assert(workflow.includes('FIREBASE_SERVICE_ACCOUNT_CSTR_CLASS_RECORD_GLOBAL'));
console.log('PASS Hosting uses a packaged canonical workspace with framing headers; CI tests rules and deploys canonical hosting before the legacy entry.');
const {execFileSync}=require('node:child_process');
for(const script of ['tools/build-web.mjs','tools/build-pages.mjs','tools/build-mobile.mjs'])execFileSync(process.execPath,[script],{cwd:root,stdio:'pipe'});
const site=path.join(root,'site-dist'),pages=path.join(root,'pages-dist');
const faculty=fs.readFileSync(path.join(site,'cst-r/index.html'),'utf8');
const signup=fs.readFileSync(path.join(site,'register/index.html'),'utf8');
assert(faculty.includes('<base href="/">'));
assert(faculty.includes('name="cstr-legacy-approval" content="deployed-rules"'));
const mobile=fs.readFileSync(path.join(root,'www/index.html'),'utf8');
assert(mobile.includes('name="cstr-legacy-approval" content="deployed-rules"'),'Android updates must preserve current faculty approvals');
assert(signup.includes('name="cstr-mode" content="closed"'));
assert(!fs.readdirSync(path.join(site,'downloads')).some(file=>file.endsWith('.apk')),'Spark Hosting must never receive APKs');
assert(fs.readdirSync(path.join(pages,'downloads')).some(file=>file.endsWith('.apk')),'Installed apps still need their Pages APK URLs');
const entry=fs.readFileSync(path.join(pages,'index.html'),'utf8');
assert(entry.includes('https://cstr-class-record-global.web.app/'));assert(!entry.includes('ASSETS/app.js'));assert(!fs.existsSync(path.join(pages,'ASSETS')));
assert.equal(fs.readFileSync(path.join(site,'downloads/latest.json'),'utf8'),fs.readFileSync(path.join(pages,'downloads/latest.json'),'utf8'));
console.log('PASS Canonical package excludes APKs; Pages retains downloads and only links to the same protected workspace.');
